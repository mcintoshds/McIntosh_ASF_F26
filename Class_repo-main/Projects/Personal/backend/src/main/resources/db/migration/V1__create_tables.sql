CREATE TABLE cuisines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    cuisine_id BIGINT NOT NULL REFERENCES cuisines(id),
    prep_minutes INTEGER NOT NULL CHECK (prep_minutes BETWEEN 0 AND 1440),
    cook_minutes INTEGER NOT NULL CHECK (cook_minutes BETWEEN 0 AND 1440),
    extra_minutes INTEGER NOT NULL CHECK (extra_minutes BETWEEN 0 AND 10080),
    servings INTEGER NOT NULL CHECK (servings BETWEEN 1 AND 100),
    instructions TEXT NOT NULL,
    image_path VARCHAR(120),
    notes TEXT NOT NULL DEFAULT '',
    tried BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE recipe_ingredients (
    recipe_id BIGINT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    ingredient VARCHAR(300) NOT NULL,
    PRIMARY KEY (recipe_id, position)
);

CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE recipe_tags (
    recipe_id BIGINT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tags(id),
    PRIMARY KEY (recipe_id, tag_id)
);

CREATE INDEX recipes_cuisine_index ON recipes(cuisine_id);
